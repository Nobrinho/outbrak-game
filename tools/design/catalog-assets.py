"""Verify and index the project asset kit. Run after both asset builders.
Creates a reproducible manifest, a Luau catalog and contact sheet for 3D renders.
"""
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
ROOT=Path(__file__).resolve().parents[2]
OUT=ROOT/'assets/game'
published_path=OUT/'published-images.json'
published=json.loads(published_path.read_text()) if published_path.exists() else {}
records=[]
for path in sorted(OUT.rglob('*')):
    if not path.is_file() or path.suffix not in ('.png','.svg','.fbx','.blend'): continue
    if path.name.endswith('.blend1') or 'contact-sheet' in path.name: continue
    rel=path.relative_to(OUT).as_posix()
    item={'key':str(Path(rel).with_suffix('')).replace('/','.'),'path':'assets/game/'+rel,'bytes':path.stat().st_size,'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'status':'local-ready-not-uploaded'}
    if path.suffix=='.png':
        with Image.open(path) as im:
            im.verify()
        with Image.open(path) as im:
            item.update(width=im.width,height=im.height,mode=im.mode)
            if rel.startswith(('ui/icons/','weapons/','hub/','vfx/')):
                assert im.mode=='RGBA',rel
                alpha=im.getchannel('A'); assert alpha.getextrema()[0]==0,rel
    if path.suffix=='.png' and item['key'] in published:
        item.update(status='uploaded',robloxId=published[item['key']])
    records.append(item)
manifest={'version':'0.1','published':bool(published),'image_ids':published,'assets':records,'existing_3d_weapons':'assets/export/weapons.fbx','model_report':'assets/game/hub/model-report.json','notes':['Native UI SVG source and PNG have identical logical keys; runtime catalog uses PNG only.','Publication IDs are preserved in published-images.json and hub/published-meshes.json. See docs/design/ASSET-INTEGRATION.md for runtime validation.']}
(OUT/'manifest.json').write_text(json.dumps(manifest,indent=2,ensure_ascii=False)+'\n')
luau=['--!strict','-- Generated by tools/design/catalog-assets.py. Source files are local; upload IDs separately.','local Assets = {}','Assets.FILES = table.freeze({']
for r in records:
    if r['path'].endswith('.png'):
        luau.append(f'\t["{r["key"]}"] = "{r["path"]}",')
luau+=['})','','-- Returns nil until an actual uploaded ID is supplied. Never pass a filesystem path to Image.','function Assets.resolve(key: string, publishedIds: { [string]: number }): string?','\tif Assets.FILES[key] == nil then','\t\treturn nil','\tend','\tlocal id = publishedIds[key]','\tif id == nil or id <= 0 or id % 1 ~= 0 then','\t\treturn nil','\tend','\treturn "rbxassetid://" .. tostring(id)','end','','return Assets','']
(ROOT/'src/client/UI/Assets.luau').write_text('\n'.join(luau))
# Only combine native Blender renders, not generated marketing art.
paths=sorted((OUT/'weapons').glob('*.png'))+sorted((OUT/'hub').glob('*.png'))
board=Image.new('RGB',(1200,((len(paths)+4)//5)*240+60),'#151820')
d=ImageDraw.Draw(board); font=ImageFont.truetype('/System/Library/Fonts/Supplemental/Arial Narrow.ttf',21)
for idx,path in enumerate(paths):
    im=Image.open(path).convert('RGBA'); im.thumbnail((205,205))
    x=idx%5*240+17; y=idx//5*240+5
    board.paste(im,(x,y),im);d.text((x+4,y+207),path.stem,font=font,fill='#ECE8DE')
d.text((24,board.height-40),'OUTBREAK / WEAPONS + CAMP / LOCAL ASSET KIT',font=font,fill='#FFCC00')
board.save(OUT/'model-contact-sheet.png')
print(json.dumps({'files':len(records),'png':sum(r['path'].endswith('.png') for r in records),'fbx':sum(r['path'].endswith('.fbx') for r in records),'svg':sum(r['path'].endswith('.svg') for r in records)},indent=2))
