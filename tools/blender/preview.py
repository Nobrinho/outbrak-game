"""Export flat-shaded Blender meshes to an exact-geometry Studio preview script.

Local validation only: final published assets must use the Studio importer.
"""
import json


def write_preview(meshes, output):
    payload = []
    for obj in meshes:
        mesh = obj.data
        mesh.calc_loop_triangles()
        points = [obj.matrix_world @ vertex.co for vertex in mesh.vertices]
        converted = [[p.x, p.z, -p.y] for p in points]
        lo = [min(p[i] for p in converted) for i in range(3)]
        hi = [max(p[i] for p in converted) for i in range(3)]
        center = [(lo[i] + hi[i]) / 2 for i in range(3)]
        color = obj.data.materials[0].diffuse_color
        payload.append({
            "name": obj.name,
            "center": center,
            "vertices": [[p[i] - center[i] for i in range(3)] for p in converted],
            "triangles": [list(tri.vertices) for tri in mesh.loop_triangles],
            # Blender diffuse colors are scene-linear, Roblox Color3 uses sRGB.
            "color": [12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055 for c in color[:3]],
        })
    (output / "pipeline_barrel.geometry.json").write_text(json.dumps(payload) + "\n")
    code = '''-- Generated by Blender. Studio Edit-mode preview only; not a published mesh.
local AssetService = game:GetService("AssetService")
local HttpService = game:GetService("HttpService")
assert(not workspace:FindFirstChild("ArtPipelinePreview"), "Preview already exists")
local data = HttpService:JSONDecode([==[PAYLOAD]==])
local model = Instance.new("Model")
model.Name = "ArtPipelinePreview"
model:SetAttribute("PreviewOnly", true)
model:SetAttribute("Source", "Blender 4.5 / pipeline_barrel")
local origin = Vector3.new(300, 10, 0)
local ok, err = pcall(function()
    for _, item in data do
        local mesh = assert(AssetService:CreateEditableMesh(), "EditableMesh unavailable")
        local ids = {}
        for i, point in item.vertices do
            ids[i] = mesh:AddVertex(Vector3.new(point[1], point[2], point[3]))
        end
        for _, tri in item.triangles do
            local a, b, c = ids[tri[1]+1], ids[tri[2]+1], ids[tri[3]+1]
            local face = mesh:AddTriangle(a, b, c)
            local normal = (mesh:GetPosition(b)-mesh:GetPosition(a)):Cross(mesh:GetPosition(c)-mesh:GetPosition(a)).Unit
            local n = mesh:AddNormal(normal)
            mesh:SetFaceNormals(face, {n,n,n})
        end
        local part = AssetService:CreateMeshPartAsync(Content.fromObject(mesh))
        part.Name = item.name
        part.Anchored = true
        part.CanCollide = false
        part.CanTouch = false
        part.CanQuery = false
        part.Color = Color3.new(item.color[1], item.color[2], item.color[3])
        part.Material = Enum.Material.SmoothPlastic
        part.CFrame = CFrame.new(origin + Vector3.new(item.center[1], item.center[2], item.center[3]))
        part.Parent = model
        task.wait()
    end
end)
if not ok then model:Destroy(); error(err) end
model.WorldPivot = CFrame.new(origin)
model.Parent = workspace
game:GetService("Selection"):Set({model})
workspace.CurrentCamera.CFrame = CFrame.lookAt(origin + Vector3.new(6,4,7), origin + Vector3.new(0,1.6,0))
local _, size = model:GetBoundingBox()
return {name=model.Name, meshCount=#model:GetChildren(), dimensions=tostring(size), pivot=tostring(model:GetPivot().Position)}
'''.replace("PAYLOAD", json.dumps(payload, separators=(",", ":")))
    (output / "pipeline_barrel.preview.luau").write_text(code)
